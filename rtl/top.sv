    output wire        hdmi_clk,
    output wire        hdmi_hs,
    output wire        hdmi_vs,
    output wire        hdmi_de,
    output wire [23:0] hdmi_d,
    inout  wire        hdmi_scl,
    inout  wire        hdmi_sda,
    output wire        hdmi_init_done
);

    // -------------------------------------------------------------------------
    // 1. PCIe Reference Clock Buffer (IBUFDS_GTE2 Primitive)
    // -------------------------------------------------------------------------
    wire pcie_ref_clk;
    IBUFDS_GTE2 u_ibufds_gte2 (
        .I     (sys_clk_clk_p),
        .IB    (sys_clk_clk_n),
        .CEB   (1'b0),
