        .pci_exp_txn     (pci_exp_txn),

        // Interrupt Ports
        .usr_irq_req     (usr_irq_req),
        .usr_irq_ack     (usr_irq_ack),
        .msi_enable      (),
        .msi_vector_width(),

        // BAR0 AXI4-Lite Control Bus (Mailbox 0x3F00)
        .m_axil_awaddr   (xdma_axil.awaddr),
