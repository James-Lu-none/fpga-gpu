        .m_axi_awprot    (xdma_m_axi.awprot),
        // .m_axi_awqos     (xdma_m_axi.awqos),
        // .m_axi_awregion  (xdma_m_axi.awregion),
        .m_axi_awvalid   (xdma_m_axi.awvalid),
        .m_axi_awready   (xdma_m_axi.awready),
